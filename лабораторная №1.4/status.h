#ifndef STATUS_H
#define STATUS_H

typedef enum {
    STATUS_OK = 0,
    STATUS_ERR_NULL_ARGUMENT,
    STATUS_ERR_FLAG_FORMAT,
    STATUS_ERR_FLAG_UNKNOWN,
    STATUS_ERR_VALUE_OUT_OF_RANGE,
    STATUS_ERR_COMPUTE_OVERFLOW,
    STATUS_ERR_ALLOC_FAILED,
    STATUS_ERR_PATH_EMPTY,
    STATUS_ERR_PATH_NO_FILENAME,
    STATUS_ERR_SAME_FILE,
    STATUS_ERR_INPUT_OPEN_FAILED,
    STATUS_ERR_OUTPUT_OPEN_FAILED,
    STATUS_ERR_READ_FAILED,
    STATUS_ERR_WRITE_FAILED,
    STATUS_ERR_CLOSE_FAILED
} Status;

const char *status_message(const Status status);

#endif
