#ifndef STATUS_H
#define STATUS_H

typedef enum {
    STATUS_OK = 0,
    STATUS_ERR_NULL_ARGUMENT,
    STATUS_ERR_NUMBER_INVALID,
    STATUS_ERR_NUMBER_OUT_OF_RANGE,
    STATUS_ERR_NUMBER_NOT_FINITE,
    STATUS_ERR_EPS_NOT_POSITIVE,
    STATUS_ERR_VALUE_OUT_OF_RANGE,
    STATUS_ERR_COMPUTE_OVERFLOW,
    STATUS_ERR_NOT_CONVERGED,
    STATUS_ERR_SERIES_DIVERGES,
    STATUS_ERR_PRECISION_UNREACHABLE
} Status;

const char *status_message(const Status status);

#endif
